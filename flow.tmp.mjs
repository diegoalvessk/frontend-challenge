import { chromium } from 'playwright'
const SP = process.argv[2]
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('[pageerror] ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') console.log('[error] ' + m.text()) })
await page.goto('http://localhost:5199/nft/emerald-ape-042')
await page.getByRole('button', { name: 'COMPRAR' }).click()
await page.waitForURL('**/carrinho')
console.log('cart ok')
await page.getByRole('button', { name: 'Conectar e finalizar' }).click()
await page.waitForURL('**/entrar**')
await page.getByPlaceholder('contato@email.com').fill('ana@kurio.dev')
await page.getByPlaceholder('Senha').fill('Kurio@2026')
await page.getByRole('button', { name: 'Entrar', exact: true }).click()
await page.waitForURL('**/pagamento')
await page.waitForSelector('[data-testid=quote-lines]')
await page.screenshot({ path: `${SP}/shots/pay-1440.png`, fullPage: true })
await page.getByTestId('review-order').click()
await page.getByTestId('review-dialog').waitFor()
await page.screenshot({ path: `${SP}/shots/review.png` })
await page.getByTestId('confirm-order').click()
await page.waitForURL('**/pedidos/**')
await page.getByTestId('order-pending').waitFor()
console.log('pending ok')
await page.getByTestId('receipt').waitFor({ timeout: 15000 })
await page.screenshot({ path: `${SP}/shots/receipt.png`, fullPage: true })
const cart = await page.evaluate(async () => {
  const s = JSON.parse(localStorage.getItem('kurio.app.session'))
  return fetch('/api/cart', { headers: { authorization: 'Bearer ' + s.token } }).then((r) => r.json())
})
console.log('cart after:', cart.itemCount, 'live:', await page.getByTestId('live-region').textContent())
await browser.close()
